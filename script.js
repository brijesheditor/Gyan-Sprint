let currentFilter = "all";

function escapeHTML(value) {
  return String(value).replace(/[&<>"']/g, char => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  })[char]);
}

function iconHTML(app) {
  return `
    <div class="app-icon"
      style="--app-color:${app.color};--app-glow:${app.glow}">
      <img
        src="${escapeHTML(app.logo)}"
        alt="${escapeHTML(app.name)} logo"
        loading="lazy"
        onerror="this.style.display='none';this.nextElementSibling.style.display='block'">
      <span class="app-icon-fallback" style="display:none">
        ${escapeHTML(app.emoji)}
      </span>
    </div>`;
}

function renderApps() {
  const search = searchInput.value.trim().toLowerCase();

  const filteredApps = apps.filter(app => {
    const matchesSearch =
      app.name.toLowerCase().includes(search) ||
      app.subtitle.toLowerCase().includes(search);

    const matchesFilter =
      currentFilter === "all" ||
      app.category === currentFilter;

    return matchesSearch && matchesFilter;
  });

  appGrid.innerHTML = filteredApps.map(app => `
    <button class="app-card" data-app="${escapeHTML(app.name)}"
      style="--app-color:${app.color};--app-glow:${app.glow}"
      aria-label="Open ${escapeHTML(app.name)} details">

      ${app.name === "Master Sahab"
        ? '<span class="recent-badge">◴ RECENT</span>'
        : ""}

      ${iconHTML(app)}

      <span class="app-name">${escapeHTML(app.name)}</span>
      <span class="app-subtitle">${escapeHTML(app.subtitle)}</span>
    </button>
  `).join("");

  appCount.textContent =
    `${String(filteredApps.length).padStart(2, "0")} APPS`;

  emptyState.hidden = filteredApps.length !== 0;

  appGrid.querySelectorAll("[data-app]").forEach(button => {
    button.addEventListener("click", () => {
      const app = apps.find(item => item.name === button.dataset.app);
      if (app) openAppDetails(app);
    });
  });
}

function renderSidebar() {
  sideAppLinks.innerHTML = apps.map(app => `
    <a class="nav-link side-app-link"
      href="#applications"
      data-side-app="${escapeHTML(app.name)}">

      <span class="side-app-icon"
        style="--app-color:${app.color};--app-glow:${app.glow}">
        ${escapeHTML(app.emoji)}
      </span>

      <span>${escapeHTML(app.name)}</span>
    </a>
  `).join("");

  sideAppLinks.querySelectorAll("[data-side-app]").forEach(link => {
    link.addEventListener("click", event => {
      event.preventDefault();
      const app = apps.find(item =>
        item.name === link.dataset.sideApp
      );

      closeSidebar();

      if (app) openAppDetails(app);
    });
  });
}

function openSidebar() {
  document.body.classList.add("menu-open");
  document.body.style.overflow = "hidden";
}

function closeSidebar() {
  document.body.classList.remove("menu-open");
  document.body.style.overflow = "";
}

function openModal(modal) {
  modal.classList.add("show");
  document.body.classList.add("modal-open");
  document.body.style.overflow = "hidden";
}

function closeModal(modal) {
  modal.classList.remove("show");

  if (!document.querySelector(".modal-backdrop.show")) {
    document.body.classList.remove("modal-open");
    document.body.style.overflow = "";
  }
}

function openAppDetails(app) {
  const detailIcon = document.getElementById("detailIcon");

  detailIcon.innerHTML = `
    <img
      src="${escapeHTML(app.logo)}"
      alt="${escapeHTML(app.name)} logo"
      class="detail-app-logo"
      onerror="this.style.display='none';
               this.nextElementSibling.style.display='block'">

    <span style="display:none">
      ${escapeHTML(app.emoji)}
    </span>
  `;

  detailIcon.style.borderColor = app.color;
  detailIcon.style.background = app.glow;

  document.getElementById("detailTitle").textContent = app.name;

  document.getElementById("detailDescription").textContent =
    app.subtitle + ". Continue to the platform's website.";

  document.getElementById("openPlatform").href = app.url;

  openModal(appModal);
}

